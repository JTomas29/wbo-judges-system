// Análisis de una pelea (getFightAnalysis /fights/:id/analysis)
function buildJudgeRounds(base, deltas) {
  return deltas.map(([round_number, red, blue, ex, w]) => ({
    round_number,
    score_red: red,
    score_blue: blue,
    winner: red > blue ? 'red' : blue > red ? 'blue' : 'draw',
    match_exact: ex,
    match_winner: w,
  }));
}

